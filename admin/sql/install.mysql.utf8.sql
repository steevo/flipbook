CREATE TABLE IF NOT EXISTS `#__flipbook_books` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `title` varchar(255) NOT NULL DEFAULT '',
  `alias` varchar(400) NOT NULL DEFAULT '',
  `folder` varchar(255) NOT NULL DEFAULT '' COMMENT 'Dossier des pages, relatif au dossier de stockage',
  `page_count` int unsigned NOT NULL DEFAULT 0,
  `page_width` int unsigned NOT NULL DEFAULT 0 COMMENT 'Largeur des pages en taille moyenne (proportions)',
  `page_height` int unsigned NOT NULL DEFAULT 0,
  `page_offset` int NOT NULL DEFAULT 0 COMMENT 'Numéro imprimé = rang de l''image + décalage',
  `free_pages` int NOT NULL DEFAULT -1 COMMENT 'Pages visibles sans droit d''accès (-1 = réglage global)',
  `description` mediumtext,
  `access` int unsigned NOT NULL DEFAULT 1,
  `state` tinyint NOT NULL DEFAULT 1,
  `ordering` int NOT NULL DEFAULT 0,
  `language` char(7) NOT NULL DEFAULT '*',
  `hits` int unsigned NOT NULL DEFAULT 0,
  `params` text,
  `created` datetime NOT NULL,
  `created_by` int unsigned NOT NULL DEFAULT 0,
  `modified` datetime NOT NULL,
  `modified_by` int unsigned NOT NULL DEFAULT 0,
  `checked_out` int unsigned,
  `checked_out_time` datetime,
  PRIMARY KEY (`id`),
  KEY `idx_state` (`state`),
  KEY `idx_access` (`access`),
  KEY `idx_alias` (`alias`(100))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 DEFAULT COLLATE=utf8mb4_unicode_ci;
